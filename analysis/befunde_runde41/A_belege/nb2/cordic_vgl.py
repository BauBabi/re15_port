def lut(z):
    s = 1
    if z < 0: z, s = -z, -1
    if z <= 4096: ang = ATAN[z >> 4]
    else: ang = 0x400 - ATAN[(4096*4096 // z) >> 4]
    return s * ang
diff = {}
mx = 0
for z in range(-200000, 200001, 7):
    c = cordic(z); l = lut(z)
    d = c - l
    diff[d] = diff.get(d, 0) + 1
    mx = max(mx, abs(d))
print('max |cordic-lut| =', mx)
print(sorted(diff.items())[:20])
print('cordic(8192)=', cordic(8192), 'lut=', lut(8192), ' cordic(0)=', cordic(0), ' cordic(4096)=', cordic(4096), 'lut', lut(4096))
