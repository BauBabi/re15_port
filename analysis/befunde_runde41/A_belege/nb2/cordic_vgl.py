# Vergleich CORDIC-catan (PSX.EXE @0x800658fc, Tabelle @0x80078c90) gegen die ATAN256-LUT von rotor_common.c
import math
TAB = [511, 302, 159, 81, 41, 20, 10, 5, 3, 1, 0, 0]
def asr(v, n): return v >> n   # Python >> ist arithmetisch
def cordic(a):
    x, y, z = 0x1000, a, 0
    for i in range(12):
        if y >= 0:
            x, y, z = x + asr(y, i), y - asr(x, i), z + TAB[i]
        else:
            x, y, z = x - asr(y, i), y + asr(x, i), z - TAB[i]
        # 32-bit wrap ignorieren (Werte klein)
    return z
