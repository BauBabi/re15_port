def dis(start, end, label):
    n_tab = struct.unpack_from("<H", d, start)[0]
    nsub = n_tab//2
    offs = [struct.unpack_from("<H", d, start+2*i)[0] for i in range(nsub)]
    print("=== %s @0x%X..0x%X (size %d)  table=%d entries: %s" % (label,start,end,end-start,nsub,
        ", ".join("0x%X"%o for o in offs)))
    for si,o in enumerate(offs):
        b = start+o
        e = start+offs[si+1] if si+1<len(offs) else end
        print("  --- sub%02d @+0x%X (file 0x%X..0x%X, %d B)" % (si,o,b,e,e-b))
        pc = b
        while pc < e:
            op = d[pc]
            sz = SZ.get(op, 1)
            nm = NM.get(op, "OP_%02X?" % op)
            args = d[pc+1:pc+sz]
            print("    +0x%04X  %02x %-18s %s" % (pc-start, op, nm, " ".join("%02x"%x for x in args)))
            pc += sz

