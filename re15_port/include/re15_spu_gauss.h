/* Zaehler einer SPU-Stimme: pos = Counter.Bit12 und hoeher (Index der Probe "new"), frac = Counter.Bit0..11,
 * alt[0..2] = oldest, older, old. */
typedef struct {
    int      pos;
    uint32_t frac;
    int16_t  alt[3];
} re15_spu_zaehler_t;

/* Key-On: Zaehler auf 0, Verlauf leer (Referenzmodell spu_ref.py: hist = [0, 0, 0, pcm[0]], counter = 0). */
static inline void re15_spu_zaehler_start(re15_spu_zaehler_t *z)
{
    z->pos = 0; z->frac = 0; z->alt[0] = z->alt[1] = z->alt[2] = 0;
}

/* psx-spx "4-Point Gaussian Interpolation": i = Counter.Bit4..11. pcm[z->pos] muss gueltig sein (pos < Laenge). */
static inline int32_t re15_spu_gauss_wert(const re15_spu_zaehler_t *z, const int16_t *pcm)
{
    const unsigned i = (unsigned)(z->frac >> 4) & 0xffu;
    int32_t out = ((int32_t)re15_spu_gauss[0x0ff - i] * z->alt[0]) >> 15;
    out += ((int32_t)re15_spu_gauss[0x1ff - i] * z->alt[1]) >> 15;
    out += ((int32_t)re15_spu_gauss[0x100 + i] * z->alt[2]) >> 15;
    out += ((int32_t)re15_spu_gauss[0x000 + i] * pcm[z->pos]) >> 15;
    return out;
}

/* psx-spx "Pitch Counter": Step = VxPitch, hoechstens 4000h; je Ueberlauf von Bit 12 rueckt eine Probe nach.
 * Ende der Probe: mit Schleife (loop_start im Bereich, Flag-Bits 0+1) weiter ab loop_start, sonst Rueckgabe 0 =
 * Stimme stumm (Flag-Bit 1 = 0: "Force Release and set ADSR Level to Zero"). */
static inline int re15_spu_zaehler_weiter(re15_spu_zaehler_t *z, const int16_t *pcm, int len, int loop_start, uint32_t pitch)
{
    if (pitch > 0x4000u) pitch = 0x4000u;
    z->frac += pitch;
    while (z->frac >= 0x1000u) {
        z->frac -= 0x1000u;
        z->alt[0] = z->alt[1]; z->alt[1] = z->alt[2]; z->alt[2] = pcm[z->pos];
        if (++z->pos >= len) {
            if (loop_start >= 0 && loop_start < len) z->pos = loop_start;
            else { z->pos = len; return 0; }
        }
    }
    return 1;
}

