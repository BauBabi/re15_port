/* re15_spu_gauss.h — Strang "ton", Stufe 5 (2026-11-20): Pitch-Zaehler und 4-Punkt-Gauss-Interpolation des PSX-Tonchips (SPU)
 * fuer jede Stimme, die im Original durch die SPU laeuft: Geraeusche (RE1.5- und RE2-Baenke) und Musik (SsSeq-Stimmen).
 * Sprachaufnahmen (synchro, XA) und Film-Ton laufen im Original ueber den CD-Eingang der SPU, nicht ueber eine Stimme -
 * sie bleiben, wie sie sind.
 *
 * Nutzer 19.11.2026: "Bei der PC Version klingen die Sounds irgendwie dumpfer/anders als in der PSX Version."
 * Messbericht U5 (scratchpad ton_dumpf/BERICHT.md): der Port nahm bei Geraeuschen den naechsten Wert (Treppenstufen), bei
 * Musik eine gerade Linie; das Original glaettet mit der Gauss-Tabelle. Rolltor: im Port oberhalb 3 kHz rund 20 dB mehr
 * Stoeranteile, Schritte oberhalb 5 kHz 40-50 dB mehr.
 *
 * Hardware-Beschreibung: info/Resident_Evil_und_Playstation_Information/psx-spx.github.io-master/docs/soundprocessingunitspu.md
 *   "Pitch Counter" (Z. 187-201):  Step = VxPitch; IF Step>3FFFh then Step=4000h; Counter = Counter + Step;
 *                                  "Counter.Bit12 and up indicates the current sample",
 *                                  "Counter.Bit4..11 are used as 8bit gaussian interpolation index".
 *                                  (PMON/Tonhoehen-Modulation benutzt das Spiel nicht - nicht nachgebaut.)
 *   "4-Point Gaussian Interpolation" (Z. 215-224):
 *        out =       ((gauss[0FFh-i] * oldest) SAR 15)
 *        out = out + ((gauss[1FFh-i] * older)  SAR 15)
 *        out = out + ((gauss[100h+i] * old)    SAR 15)
 *        out = out + ((gauss[000h+i] * new)    SAR 15)
 *   Tabelle (Z. 226-290): 512 Werte, unten Zeile fuer Zeile aus der Datei uebernommen (erzeugt mit dem Leser des
 *   Referenzmodells ton_dumpf/skripte/spu_ref.py gauss_table; der Riegel unit_r42_ton_gauss liest die Datei erneut und
 *   vergleicht alle 512 Werte).
 *   "SPU ADPCM Samples", Flag-Bits (Z. 130-132): Bit0 Loop End = Sprung zur Wiederhol-Adresse; Bit1 Loop Repeat = 0 ->
 *   "Force Release and set ADSR Level to Zero": eine Einmal-Probe ist in dem Augenblick STUMM, in dem der Zaehler ueber
 *   ihre letzte Probe hinauslaeuft (kein Ausblenden).
 *
 * Abfolge je Ausgabeprobe (44100 Hz) wie im Referenzmodell spu_ref.py spu_voice (Treffer am Original 0,99994):
 *   1. Wert = re15_spu_gauss_wert(z, pcm)       (new = pcm[z->pos], old/older/oldest = die drei zuvor gespielten Proben)
 *   2. re15_spu_zaehler_weiter(z, ..., pitch)   (Zaehler += min(pitch, 0x4000); je volle 0x1000 rueckt eine Probe nach)
 * Vor dem ersten Wert sind old/older/oldest 0 (Referenzmodell; psx-spx sagt dazu nichts - offen, Abweichung hoechstens in
 * den ersten 3 Proben einer Stimme).
 */
