#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""kanister2080_se_cut.py - Runde 41 Spur G: der Aufschlag des Gaskanisters im Wasser aus der RE2-Raumbank
ROOM40A0 (info/re2leon/PL0/RDT/ROOM40A0.RDT, snd0: EDT @0x9DE0 / VH @0x9EA0 / VB @0xACC0) als Mini-Bank
shared_assets/RE2/KANISTER2080.VBS (Satzformat wie TUERSE.VBS / GATOR40A0.VBS, Laderpaar platform/pc/src/kanister2080_pc.c).

  Satz 0 = ROOM40A0 EDT-Satz 11 `00 01 83 00` = AUFSCHLAG IM WASSER: RE2 ROOM40A0 sub10 (Kanister faellt vom Halter ins
           Wasser) `36 02 0b 01 04 01 ..` @SCD-main 0x0686, direkt nach der Fall-Schleife For 23 @0x0676.
Mehrlagige Saetze (Byte 3 >> 5 Zusatzlagen, FUN_80045024 @0x8004548c) werden als zusammenhaengende
Ton-Laeufe uebernommen; nur Byte 1 (Programm -> 0), Byte 2 oberes Nibble (Tonindex) und Tone+0x16
(VAG-Index, 1-basiert) werden umgesetzt. Alles andere bytegleich (Vorlage tools/r41_re2gator/gator40a0_se_cut.py).

Aufruf: python re15_port/tools/r41_kanister2080/kanister2080_se_cut.py [--install]
"""
import hashlib, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
RDT = os.path.join(REPO, "info", "re2leon", "PL0", "RDT", "ROOM40A0.RDT")
VAB_HDR = 32; VAB_PROG_TABLE = 128 * 16; VAB_TONE_SEG = 16 * 32; VAB_SIZE_TABLE = 256 * 2
VH_SIZE = VAB_HDR + VAB_PROG_TABLE + VAB_TONE_SEG + VAB_SIZE_TABLE
SE_MAP_BYTES = 0x20
SAETZE = [("PLATSCH", 11, "00018300")]

def die(m): sys.stderr.write("kanister2080_se_cut: FEHLER: %s\n" % m); sys.exit(1)

def main():
    install = "--install" in sys.argv
    a = open(RDT, "rb").read()
    edt, vh, vb = struct.unpack_from("<III", a, 8)
    if (edt, vh, vb) != (0x9DE0, 0x9EA0, 0xACC0): die("Sektionsoffsets weichen ab: %x %x %x" % (edt, vh, vb))
    if a[vh:vh+4] != b"pBAV": die("kein pBAV")
    nprog = struct.unpack_from("<H", a, vh + 0x12)[0]
    sizetab = vh + 0x820 + nprog * 0x200
    se_map = bytearray(SE_MAP_BYTES); vh_out = bytearray(VH_SIZE); vbd = bytearray()
    vag_neu = {}          # alter VAG-Index -> (neuer Index 1-basiert)
    ton_n = 0; rows = []
    for si, (name, rec, hexraw) in enumerate(SAETZE):
        raw = a[edt + rec*4: edt + rec*4 + 4]
        if raw.hex() != hexraw: die("Satz %d: %s != %s" % (rec, raw.hex(), hexraw))
        prog = raw[1] & 0x7F; tone = raw[2] >> 4; lagen = (raw[3] >> 5) + 1
        erst = ton_n
        for k in range(lagen):
            t = bytearray(a[vh + 0x820 + prog*0x200 + (tone+k)*0x20:][:32])
            vagi = struct.unpack_from("<H", t, 0x16)[0]
            if vagi not in vag_neu:
                pos = vb
                for j in range(vagi): pos += struct.unpack_from("<H", a, sizetab + j*2)[0] << 3
                ln = struct.unpack_from("<H", a, sizetab + vagi*2)[0] << 3
                wav = a[pos:pos+ln]
                vag_neu[vagi] = (len(vag_neu) + 1, pos, ln, hashlib.sha1(wav).hexdigest())
                struct.pack_into("<H", vh_out, VAB_HDR + VAB_PROG_TABLE + VAB_TONE_SEG + 2 * vag_neu[vagi][0], ln // 8)
                vbd += wav
            struct.pack_into("<H", t, 0x16, vag_neu[vagi][0])
            vh_out[VAB_HDR + VAB_PROG_TABLE + ton_n*32: VAB_HDR + VAB_PROG_TABLE + (ton_n+1)*32] = t
            ton_n += 1
        r = bytearray(raw); r[1] = 0; r[2] = ((erst & 0xF) << 4) | (raw[2] & 0x0F)
        se_map[si*4: si*4+4] = r
        rows.append((si, name, rec, raw.hex(" "), bytes(r).hex(" "), prog, tone, lagen,
                     [(v, vag_neu[v][1], vag_neu[v][2], vag_neu[v][3][:12]) for v in sorted(vag_neu)]))
    hdr = a[vh:vh+32]; prog0 = a[vh+32:vh+48]
    vh_out[0:4] = b"pBAV"; vh_out[4:8] = hdr[4:8]; vh_out[8:12] = hdr[8:12]
    struct.pack_into("<I", vh_out, 12, VH_SIZE + len(vbd)); vh_out[16:18] = hdr[16:18]
    struct.pack_into("<H", vh_out, 18, 1); struct.pack_into("<H", vh_out, 20, 16)
    struct.pack_into("<H", vh_out, 22, len(vag_neu)); vh_out[24] = hdr[24]; vh_out[25] = hdr[25]; vh_out[26:32] = hdr[26:32]
    vh_out[VAB_HDR:VAB_HDR+16] = prog0; vh_out[VAB_HDR] = ton_n
    edt_rec = bytes(se_map) + bytes(vh_out) + struct.pack("<II", SE_MAP_BYTES, 0)
    out_dir = os.path.join(REPO, "re15_port", "shared_assets", "RE2") if install else os.path.join(REPO, "build", "r41_kanister2080")
    inc_dir = os.path.join(REPO, "re15_port", "engine", "src", "gen") if install else out_dir
    os.makedirs(out_dir, exist_ok=True); os.makedirs(inc_dir, exist_ok=True)
    out_vbs = os.path.join(out_dir, "KANISTER2080.VBS"); out_inc = os.path.join(inc_dir, "r41_kanister2080_bank.inc")
    open(out_vbs, "wb").write(edt_rec + bytes(vbd))
    with open(out_inc, "w", newline="\n") as o:
        o.write("/* AUTO-GENERATED by re15_port/tools/r41_kanister2080/kanister2080_se_cut.py -- DO NOT EDIT.\n"
                " * Mini-Bank shared_assets/RE2/KANISTER2080.VBS = ROOM40A0-Raumbank Satz 11 (RE2 ROOM40A0 sub10 Se_on @SCD 0x0686).\n"
                " * [SE-Map @0 .. vh_off)[VH pBAV @vh_off][Trailer u32 vh_off @size-8][VBD]. */\n")
        for (si, name, rec, rawh, neuh, prog, tone, lagen, vags) in rows:
            o.write(" /* Satz %d %-9s ROOM40A0 EDT %d  %s -> %s  Prog %d Ton %d Lagen %d  VAGs %s */\n"
                    % (si, name, rec, rawh, neuh, prog, tone, lagen, vags))
        o.write("#define R41_K2080_EDT_SIZE  %du\n#define R41_K2080_VBD_OFF   %du\n#define R41_K2080_VBD_SIZE  %du\n"
                % (len(edt_rec), len(edt_rec), len(vbd)))
        o.write("#define R41_K2080_SE_PLATSCH    0   /* ROOM40A0 Satz 11 (sub10 Se_on 36 02 0b 01 04 01 @SCD 0x0686) */" + chr(10))
    for r in rows: print("  Satz", r[0], r[1], "EDT", r[2], r[3], "->", r[4], "Prog", r[5], "Ton", r[6], "Lagen", r[7], r[8])
    print("  %s: edt %d B, vbd %d B, gesamt %d B, md5 %s" % (out_vbs, len(edt_rec), len(vbd), len(edt_rec)+len(vbd),
          hashlib.md5(edt_rec + bytes(vbd)).hexdigest()))
if __name__ == "__main__": main()
