#!/usr/bin/env python3
"""Generate engine/src/gen/ems_toc_r37.inc -- die beiden Modellarchiv-TOCs der RE1.5-EXE (Runde 37 Spur K).

Quelle: info/Re1.5/PSX.EXE (Auslieferungsstand; Datei-Offset = 0x800 + RAM - t_addr, t_addr @Header 0x18).
Lader FUN_80022300 (Sce_em_set -> `jal 0x80022300` @0x80042328):
    80022324  lbu  v0,8(s2)            Typ
    8002232c  lw   v1,-13764(v1)       DAT_800aca3c
    80022334  bltz v1,0x800223ac       Bit 31 = Elza-Bit
    80022338  addiu a0,v0,-16          Index = Typ - 0x10
  Leon: 8002233c ori v0,zero,0x26 (Datei 0x26 = EMD/CDEMD0.EMS, LBA 1316),
        Laenge @0x80072f3c+i*8 (80022354), Sektor @0x80072f38+i*8 (80022370)
  Elza: 800223ac ori v0,zero,0x27 (Datei 0x27 = EMD/CDEMD1.EMS, LBA 3627),
        Laenge @0x8007317c+i*8 (800223c4), Sektor @0x80073178+i*8 (800223e0)
Je Tabelle 64 Eintraege {u32 sektor_im_archiv, u32 byte_laenge} fuer Typ 0x10..0x4F (endet am
Byte-Array @0x80073138 bzw. @0x80073378). Rohe u32 exakt wie in der EXE.
Byte-Anker (hart geprueft): Typ 0x47 Leon (1644, 127640), Elza (1639, 142272);
Typ 0x10 Leon (0, 214496), Elza (0, 214816).
"""
import os, struct, sys
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
EXE = os.path.join(REPO, 'info', 'Re1.5', 'PSX.EXE')
OUT = os.path.join(REPO, 're15_port', 'engine', 'src', 'gen', 'ems_toc_r37.inc')
exe = open(EXE, 'rb').read()
t_addr = struct.unpack_from('<I', exe, 0x18)[0]
def tab(addr):
    o = 0x800 + addr - t_addr
    return list(struct.unpack_from('<128I', exe, o))
leon, elza = tab(0x80072f38), tab(0x80073178)
i47 = (0x47 - 0x10) * 2
assert (leon[i47], leon[i47+1]) == (1644, 127640), (leon[i47], leon[i47+1])
assert (elza[i47], elza[i47+1]) == (1639, 142272), (elza[i47], elza[i47+1])
assert (leon[0], leon[1]) == (0, 214496) and (elza[0], elza[1]) == (0, 214816)
def emit(name, vals, kommentar):
    s = '/* %s */\nstatic const uint32_t %s[128] = {\n' % (kommentar, name)
    for k in range(0, 128, 8):
        s += '    ' + ', '.join('0x%08xu' % v for v in vals[k:k+8]) + ',\n'
    return s + '};\n'
txt = ('/* AUTO-GENERATED by tools/r37_k/gen_ems_toc_r37.py -- DO NOT EDIT.\n'
       ' * Quelle: info/Re1.5/PSX.EXE (t_addr 0x%08x). {sektor, laenge} je Typ 0x10..0x4F,\n'
       ' * Zugriff in roy_r37.c (re15_ems_toc). */\n' % t_addr)
txt += emit('s_ems_toc_leon', leon, 'CDEMD0.EMS (Datei 0x26) -- TOC @0x80072f38, Leon (DAT_800aca3c Bit 31 = 0)')
txt += emit('s_ems_toc_elza', elza, 'CDEMD1.EMS (Datei 0x27) -- TOC @0x80073178, Elza (DAT_800aca3c Bit 31 = 1)')
open(OUT, 'w', newline='\n').write(txt)
print('wrote', OUT)
