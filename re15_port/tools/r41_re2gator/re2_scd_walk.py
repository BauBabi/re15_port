def walk(d, base, end, label):
    n = struct.unpack_from('<H', d, base)[0] // 2
    subs = [struct.unpack_from('<H', d, base + 2*i)[0] for i in range(n)]
    print(f"== {label} @0x{base:X}  subs={n} {[hex(s) for s in subs]}")
    for i, so in enumerate(subs):
        e = subs[i+1] if i+1 < n else (end - base)
        p = base + so
        print(f"-- sub{i:02d} @0x{p:X} (len {e-so})")
