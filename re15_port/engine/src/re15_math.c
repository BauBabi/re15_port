/* BIOS rsin core (0x80068424): quarter-wave reflection of the Q0 sine table, a in [0,0xfff]. */
static int32_t re15_rsin_core(int32_t a)
{
    if (a < 0x400) return re15_sin_q0[a];
    if (a < 0x800) return re15_sin_q0[0x800 - a];
    if (a < 0xc00) return -re15_sin_q0[a - 0x800];
    return -re15_sin_q0[0x1000 - a];
}

/* BIOS rsin (0x800683e8): sign-handles then reflects. Angle 0..4095 = 360deg, Q12 result. */
int32_t re15_rsin(int32_t a)
{
    if (a < 0) return -re15_rsin_core((-a) & 0xfff);
    return re15_rsin_core(a & 0xfff);
}

/* BIOS rcos (0x80068348): cos is even; rcos(a) = rsin(|a| + 90deg). Byte-identical to the
 * BIOS quarter-wave (verified region-by-region against 0x80068348). */
int32_t re15_rcos(int32_t a)
{
    if (a < 0) a = -a;
    return re15_rsin_core((a + 0x400) & 0xfff);
}

/* BIOS ratan2 (0x80065de0): angle of the vector (x, y) measured CCW from +X, 0..4095 = 360deg.
 * Sign-tracks both components, divides the smaller by the larger scaled by 1024, looks up the
 * arctan table, then assembles the quadrant. Byte-true incl. the BIOS asymmetry (the large-value
 * guard is dead on the |y|>=|x| branch -- v0 was cleared by the branch that reaches it). */
int32_t re15_ratan2(int32_t y, int32_t x)
{
    int sx = 0, sy = 0;
    if (x < 0) { sx = 1; x = -x; }
    if (y < 0) { sy = 1; y = -y; }
    if (x == 0 && y == 0) return 0;
    int32_t v1;
    if (y < x) {                                   /* |y| < |x| : ratio y/x in [0,1) */
        int32_t idx = (y & 0x7fe00000) ? (y / (x >> 10)) : ((y << 10) / x);
        v1 = re15_atan_q10[idx];
    } else {                                       /* |y| >= |x| : angle 0x400 - atan(x/y) */
        int32_t idx = (x << 10) / y;
        v1 = 0x400 - re15_atan_q10[idx];
    }
    if (sx) v1 = 0x800 - v1;                       /* x < 0 : reflect across +Y */
    if (sy) v1 = -v1;                              /* y < 0 : reflect across +X */
    return v1;
}

/* Anisotropic-ellipse directional radius. Shared by the body-push (FUN_8002aec4 @0x8002afb8-b05c)
 * and the attack-hitbox sector test (FUN_8002b5d0 @0x8002b65c) -- byte-identical code in both.
 * The effective radius of a box (rx = box[+6] along heading, rz = box[+0xa] lateral) toward a point
 * at delta (dx,dz) from the box CENTRE, given the box heading rot_y. Circular (rx==rz) -> rx.
 *   rel = ratan2(dz,dx) - rot_y, folded to a [0,0x400] triangle wave;
 *   rz<rx: eff = rz + (rx-rz)*rcos(s4)/4096   ;   else: eff = rx + (rz-rx)*rsin(s4)/4096 */
int32_t re15_ellipse_radius(int32_t rx, int32_t rz, int32_t rot_y, int32_t dz, int32_t dx)
{
    if (rx == rz || rz <= 0) return rx;             /* circular box, or a port actor with no lateral radius */
    int32_t rel = (re15_ratan2(dz, dx) - rot_y) & 0xfff;
    int32_t s4 = (rel < 0x400) ? rel
               : (rel < 0x800) ? 0x800 - rel
               : (rel < 0xc00) ? rel - 0x800
                               : 0x1000 - rel;
    if (rz < rx) return rz + (int32_t)(((int64_t)(rx - rz) * re15_rcos(s4)) >> 12);
    return rx + (int32_t)(((int64_t)(rz - rx) * re15_rsin(s4)) >> 12);
}


