/* GTE RTPS perspective-division reciprocal (psx-spx GTE, the fast Unsigned Newton-Raphson). Returns
 * n for the projection sx = OFX + (IR1*n)>>16 (n approximates H*0x10000/SZ3). It is DELIBERATELY less
 * accurate than an exact H/z divide (the hardware UNR) -- the byte-true perspective divide, NOT a
 * float/exact one. h = the GTE H (fov>>7), sz3 = the u16 view-space z (MAC3>>12). */
uint32_t re15_gte_divide(uint32_t h, uint32_t sz3)
{
    if (sz3 == 0 || h >= sz3 * 2) return 0x1FFFF;      /* overflow / div-by-0 -> saturate */
    int z = 0; uint32_t s = sz3; while (s < 0x8000) { s <<= 1; z++; }   /* clz of the 16-bit sz3 */
    uint32_t n = h << z;                               /* 0..0x7FFF8000 */
    uint32_t d = sz3 << z;                             /* 0x8000..0xFFFF */
    uint32_t u = (uint32_t)re15_unr_table[(d - 0x7FC0) >> 7] + 0x101;
    d = (0x2000080u - d * u) >> 8;
    d = (0x0000080u + d * u) >> 8;
    n = (uint32_t)(((uint64_t)n * d + 0x8000) >> 16);
    return n > 0x1FFFF ? 0x1FFFF : n;
}

